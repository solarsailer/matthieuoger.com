function findPages(directory) {
  const urls = []

  for (const entry of readdirSync(directory, {
    recursive: true,
    withFileTypes: true
  })) {
    if (entry.name !== "index.html") continue

    const path = relative(directory, entry.parentPath).split(sep).join("/")
    urls.push(path ? `/${path}/` : "/")
  }

  return urls.sort()
}

function isRemoved(url) {
  return REMOVED_URLS.some((x) => url.startsWith(x))
}

function safeFindPages(directory) {
  try {
    return findPages(directory)
  } catch {
    return []
  }
}

